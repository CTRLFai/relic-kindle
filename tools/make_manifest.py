#!/usr/bin/env python3
"""Regenerate relic.koplugin/manifest.lua. Usage: tools/make_manifest.py [--bump]
The Kindle updater installs a new version only when this version number goes up."""
import hashlib, os, re, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "relic.koplugin")
mpath = os.path.join(root, "manifest.lua")
version = 0
if os.path.exists(mpath):
    m = re.search(r"version\s*=\s*(\d+)", open(mpath).read())
    version = int(m.group(1)) if m else 0
if "--bump" in sys.argv or version == 0:
    version += 1
files = []
for d, _, names in os.walk(root):
    for n in sorted(names):
        full = os.path.join(d, n)
        rel = os.path.relpath(full, root).replace(os.sep, "/")
        if rel == "manifest.lua" or n.startswith(".") or n.endswith(".bak"):
            continue
        data = open(full, "rb").read()
        files.append((rel, len(data), hashlib.sha256(data).hexdigest()))
files.sort()
with open(mpath, "w") as f:
    f.write("-- Generated by tools/make_manifest.py. Do not edit by hand.\nreturn {\n    version = %d,\n    files = {\n" % version)
    for rel, size, sha in files:
        f.write('        { path = "%s", size = %d, sha256 = "%s" },\n' % (rel, size, sha))
    f.write("    },\n}\n")
print("manifest version", version, "files", len(files))
